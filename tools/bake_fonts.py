#!/usr/bin/env python3
"""Bake original OFL font sources into a crisp monochrome SDL atlas."""
from pathlib import Path
import hashlib
import json
from PIL import Image, ImageDraw, ImageFont, features

root = Path(__file__).resolve().parents[1]
fontdir = root / 'assets/fonts'
width, height = 512, 384
atlas = Image.new('L', (width, height))
draw = ImageDraw.Draw(atlas)
glyphs, sources = [], []
styles = [('PixelifySans.ttf', 14, 600), ('Jersey20-Regular.ttf', 24, None)]
for style, (filename, size, weight) in enumerate(styles):
    path = fontdir / filename
    font = ImageFont.truetype(str(path), size)
    if weight:
        axes = font.get_variation_axes()
        font.set_variation_by_axes([weight if a['name'] == b'Weight' else a['default'] for a in axes])
    cap_top = font.getbbox('H')[1]
    sources.append({'file': filename, 'pixels': size, 'weight': weight,
                    'sha256': hashlib.sha256(path.read_bytes()).hexdigest()})
    for code in range(32, 127):
        char = chr(code)
        left, top, right, bottom = font.getbbox(char)
        w, h = right-left, bottom-top
        slot = style*95+code-32
        x, y = slot % 16*32, slot//16*32
        if w > 32 or h > 32:
            raise ValueError('Glyph too large for atlas cell')
        draw.text((x-left, y-top), char, font=font, fill=255)
        glyphs.append((x, y, w, h, left, top-cap_top, round(font.getlength(char))))
# Deliberately binary: each logical pixel becomes a 2x2 physical pixel on RG40XX H.
atlas = atlas.point(lambda p: 255 if p >= 128 else 0)
atlas.save(fontdir / 'beacon-atlas.png', optimize=True)
raw = atlas.tobytes()
rle, offset = [], 0
while offset < len(raw):
    end = offset+1
    while end < len(raw) and raw[end] == raw[offset] and end-offset < 255:
        end += 1
    rle.extend((end-offset, raw[offset]))
    offset = end
lines = ['// Generated by tools/bake_fonts.py. Font licenses: assets/fonts/*-OFL.txt.',
         '#pragma once', '#include <cstdint>', 'namespace typography {',
         f'inline constexpr int Width={width},Height={height};',
         'struct Glyph {int x,y,w,h,left,top,advance;};',
         'inline constexpr Glyph Glyphs[]={']
for glyph in glyphs:
    lines.append(' {'+','.join(map(str, glyph))+'},')
lines += ['};', 'inline constexpr uint8_t PixelsRle[]={']
for n in range(0, len(rle), 32):
    lines.append(' '+','.join(map(str, rle[n:n+32]))+',')
lines += ['};', '}', '']
(root / 'src/font_data.hpp').write_text('\n'.join(lines))
(fontdir / 'atlas.json').write_text(json.dumps({
    'google_fonts_commit': '47d54ca1ebb14fd864695f1d39dc734f39017c33',
    'pillow': Image.__version__, 'freetype': features.version_module('freetype2'),
    'sources': sources, 'glyphs': len(glyphs), 'dimensions': [width,height],
    'threshold': 128, 'alpha_sha256': hashlib.sha256(raw).hexdigest()}, indent=2)+'\n')
print(f'Baked {len(glyphs)} glyphs, {len(rle)} RLE bytes')
